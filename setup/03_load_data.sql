-- Create internal stage and load JSONL data
CREATE OR REPLACE STAGE DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS_STAGE
  FILE_FORMAT = (TYPE = 'JSON' STRIP_OUTER_ARRAY = FALSE);

-- Upload file (run from CLI):
--   snow stage copy data/raw_events.jsonl @DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS_STAGE --connection demo

COPY INTO DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS (NAMESPACE, BODY, RECEIVED_AT)
FROM (
  SELECT
    $1:namespace::VARCHAR,
    $1:body::VARCHAR,
    $1:received_at::VARCHAR
  FROM @DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS_STAGE/raw_events.jsonl
)
FILE_FORMAT = (TYPE = 'JSON' STRIP_OUTER_ARRAY = FALSE);

-- Verify
SELECT COUNT(*) AS row_count FROM DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS;
SELECT ID, NAMESPACE, LEFT(BODY, 120) AS body_preview, RECEIVED_AT
FROM DEMO_PARALLELS_EVENTS.PLATFORM_EVENTS.RAW_EVENTS
LIMIT 3;
