CREATE OR REPLACE DYNAMIC TABLE DEMO_PARALLELS.STAGING.STG_HOSTS_DEDUPED
  TARGET_LAG = '1 day'
  WAREHOUSE = DEMO_WH
  REFRESH_MODE = INCREMENTAL
  INITIALIZE = ON_CREATE
  COMMENT = 'Deduplicated host registry, one row per HWID'
AS
SELECT
    ID,
    HWID,
    HW_MODEL,
    OS_ARCH,
    FIRST_SEEN_AT,
    LAST_SEEN_AT,
    REGION
FROM (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY HWID ORDER BY LAST_SEEN_AT DESC) AS rn
    FROM DEMO_PARALLELS.RAW.RAW_HOSTS
)
WHERE rn = 1;
