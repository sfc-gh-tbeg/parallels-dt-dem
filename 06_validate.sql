-- Validate the demo environment
SHOW DYNAMIC TABLES IN SCHEMA DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS;

SELECT 'RAW_EVENTS' AS source, COUNT(*) AS rows FROM DEMO_ALLUDO_EVENTS.PLATFORM_EVENTS.RAW_EVENTS
UNION ALL
SELECT 'PD_EVENTS_FLAT', COUNT(*) FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.PD_EVENTS_FLAT
UNION ALL
SELECT 'INSTALLER_EVENTS_FLAT', COUNT(*) FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.INSTALLER_EVENTS_FLAT;

-- Sample PD events
SELECT * FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.PD_EVENTS_FLAT LIMIT 5;

-- Sample installer events
SELECT * FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.INSTALLER_EVENTS_FLAT LIMIT 5;

-- Event distribution
SELECT event_code, COUNT(*) AS cnt
FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.PD_EVENTS_FLAT
GROUP BY 1 ORDER BY 2 DESC;

SELECT event_code, COUNT(*) AS cnt
FROM DEMO_ALLUDO_EVENTS.FLATTENED_EVENTS.INSTALLER_EVENTS_FLAT
GROUP BY 1 ORDER BY 2 DESC;
