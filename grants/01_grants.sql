CREATE ROLE IF NOT EXISTS DBT_ETL_ROLE;
CREATE ROLE IF NOT EXISTS DA_ROLE;

-- Grant usage on database, schemas, and warehouse
GRANT USAGE ON DATABASE DEMO_PARALLELS TO ROLE DBT_ETL_ROLE;
GRANT USAGE ON DATABASE DEMO_PARALLELS TO ROLE DA_ROLE;
GRANT USAGE ON SCHEMA DEMO_PARALLELS.STAGING TO ROLE DBT_ETL_ROLE;
GRANT USAGE ON SCHEMA DEMO_PARALLELS.STAGING TO ROLE DA_ROLE;
GRANT USAGE ON SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DBT_ETL_ROLE;
GRANT USAGE ON SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DA_ROLE;
GRANT USAGE ON WAREHOUSE DEMO_WH TO ROLE DBT_ETL_ROLE;
GRANT USAGE ON WAREHOUSE DEMO_WH TO ROLE DA_ROLE;

-- Grant SELECT on all staging tables
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.STAGING TO ROLE DBT_ETL_ROLE;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.STAGING TO ROLE DA_ROLE;

-- Grant SELECT on all analytics tables
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DBT_ETL_ROLE;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DA_ROLE;

-- Future grants for any new DTs added later
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.STAGING TO ROLE DBT_ETL_ROLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.STAGING TO ROLE DA_ROLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DBT_ETL_ROLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DEMO_PARALLELS.ANALYTICS TO ROLE DA_ROLE;
