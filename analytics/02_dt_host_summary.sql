CREATE OR REPLACE DYNAMIC TABLE DEMO_PARALLELS.ANALYTICS.DT_HOST_SUMMARY
  TARGET_LAG = '1 minute'
  WAREHOUSE = DEMO_WH
AS
SELECT
    HWID,
    MAX(HW_MODEL)                AS HW_MODEL,
    MAX(ARCH)                    AS ARCH,
    MAX(OS_NAME)                 AS OS_NAME,
    MAX(VERSION)                 AS LATEST_VERSION,
    MAX(LICENSE_EDITION)         AS LICENSE_EDITION,
    MAX(LICENSE_STATUS)          AS LICENSE_STATUS,
    MIN(RECEIVED_AT)             AS FIRST_SEEN,
    MAX(RECEIVED_AT)             AS LAST_SEEN,
    COUNT(*)                     AS EVENT_COUNT
FROM DEMO_PARALLELS.ANALYTICS.DT_EVENTS_PARSED
GROUP BY HWID;
