CREATE OR REPLACE DYNAMIC TABLE DEMO_PARALLELS.ANALYTICS.AGG_LICENSE_STATUS
  TARGET_LAG = '1 day'
  WAREHOUSE = DEMO_WH
  REFRESH_MODE = INCREMENTAL
  INITIALIZE = ON_CREATE
  COMMENT = 'Current license distribution by edition, status, and region'
AS
SELECT
    l.EDITION,
    l.STATUS,
    l.TYPE,
    h.REGION,
    COUNT(DISTINCT l.LICENSE_KEY)    AS license_count,
    COUNT(DISTINCT l.HWID)          AS device_count
FROM DEMO_PARALLELS.STAGING.STG_LICENSES_FLAT l
JOIN DEMO_PARALLELS.STAGING.STG_HOSTS_DEDUPED h
  ON l.HWID = h.HWID
GROUP BY l.EDITION, l.STATUS, l.TYPE, h.REGION;
